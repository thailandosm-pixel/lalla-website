/* ============================================================
   Static pages (generated by tools/build.mjs)
   ------------------------------------------------------------
   The page already contains its full content as HTML - that is
   the point of it, for search engines. This only attaches
   behaviour: nav and footer, the quote drawer, the specs toggle,
   scroll animations and analytics. Nothing here re-renders the
   content, and the 380 KB catalogue file is never loaded.
   ============================================================ */

(function () {
  const main = document.querySelector('main[data-page]');
  if (!main) return;
  const d = main.dataset;

  mountChrome(d.active || 'products');

  if (d.page === 'product') {
    const related = d.related ? d.related.split('|') : [];
    wireQuoteButton(d.model, related);
    wireSpecsToggle();
    lallaTrack('product_view', { model: d.model, brand: d.brand, group: d.group,
      has_specs: !!document.getElementById('specsGrid') });
  } else if (d.page === 'category') {
    lallaTrack('category_view', { brand: d.brand, category: d.group, models: Number(d.count) || 0 });
  } else if (d.page === 'brand') {
    lallaTrack('brand_view', { brand: d.brand });
  } else if (d.page === 'landing') {
    wireQuoteButton(d.model, []);
    lallaTrack('landing_view', { landing: d.landing });
  }

  initReveal();
  initScrollSpy('.subnav-links a');
})();
